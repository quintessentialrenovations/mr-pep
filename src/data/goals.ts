export const GOAL_PRIORITY = ["injury", "joints", "gut", "puffiness", "weight", "recovery", "skin"] as const;

export function goalsByIds(ids: string[]): GoalGuide[] {
  const want = new Set(ids);
  const ordered = GOAL_PRIORITY.map((id) => GOALS.find((g) => g.id === id)).filter((g): g is GoalGuide => Boolean(g && want.has(g.id)));
  const extra = GOALS.filter((g) => want.has(g.id) && !ordered.some((o) => o.id === g.id));
  return [...ordered, ...extra];
}

/** Build a natural ask from tapped feelings — no peptide names required. */
export function askFromGoals(ids: string[]): string {
  const picked = goalsByIds(ids);
  if (!picked.length) return "";
  return `${picked.map((g) => g.utterance).join(". ")}. I don't know peptide names. Ask your clarifying questions first. After I answer, sequence what the books would discuss, including mitochondrial support.`;
}

